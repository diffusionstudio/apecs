/**
 * Renders REPORT.md from results.json and findings.json.
 *
 *   node report.mjs
 */
import { readFileSync, writeFileSync } from 'node:fs'

import { BENCHMARKS } from './lib/spec.mjs'

const r = JSON.parse(readFileSync('results.json', 'utf8'))
const f = JSON.parse(readFileSync('findings.json', 'utf8'))

const LIBS = ['baseline', 'apecs', 'bitecs', 'koota', 'becsy']
const TITLE = {
  baseline: 'hand-written',
  apecs: 'apecs',
  bitecs: 'bitECS',
  koota: 'koota',
  becsy: 'becsy',
}
const us = (ns) => ns / 1000

/** The fastest tier a library offers for a benchmark — its honest best. */
function best(bench, lib) {
  const entry = r.timings[bench]?.[lib]
  if (!entry) return undefined
  const times = Object.values(entry.variants)
    .filter((v) => !v.error)
    .map((v) => v.avg)
  return times.length ? Math.min(...times) : undefined
}
function tier(bench, lib, name) {
  const v = r.timings[bench]?.[lib]?.variants?.[name]
  return v && !v.error ? v.avg : undefined
}
const fmt = (ns) => (ns === undefined ? '–' : us(ns) >= 100 ? us(ns).toFixed(0) : us(ns).toFixed(1))
const ratio = (ns, base) => (ns === undefined ? '–' : (ns / base).toFixed(1) + '×')

let out = ''
const w = (s = '') => (out += s + '\n')

w('# apecs vs. the JS/TS ECS field')
w()
w(
  `> Generated by \`node report.mjs\` from \`results.json\`. Measured ${r.meta.when.slice(0, 10)} on ${r.meta.cpus}, Node ${r.meta.node} (${r.meta.platform}).`,
)
w()
w('## What is being compared')
w()
w('| Library | Version | Design |')
w('| --- | --- | --- |')
for (const lib of LIBS) {
  const any = Object.values(r.timings)
    .map((b) => b[lib])
    .find(Boolean)
  w(
    `| ${TITLE[lib]} | ${any?.version ?? 'hand-written'} | ${any?.notes ?? 'Typed arrays and index arithmetic. No entity ids, no queries, no structural change.'} |`,
  )
}
w()
w(
  'apecs is measured from its built `dist/` — the same bytes a user installs, with `__DEV__` assertions',
)
w(
  'compiled out (verified by `npm run check:bundle`). becsy is measured from its `perf` build for the',
)
w(
  'same reason: its default build carries runtime validation and benchmarking it would be dishonest.',
)
w()
w('## Method, and the two things that would have made this report wrong')
w()
w(
  '**One process per (library, benchmark).** Loading four ECS libraries into one isolate makes the shared',
)
w(
  'call sites in the iteration path megamorphic, and V8 then deoptimises whichever library warmed up',
)
w('second. That effect is larger than most of the differences being measured.')
w()
w(
  '**A fairness census, run before any timing.** Every library must match the *same number of entities*',
)
w(
  'on every query-shaped benchmark, or the run aborts. This is not a formality — it caught two real',
)
w('problems that would each have produced a fake result:')
w()
w(
  '- `Not()` in apecs takes exactly one operand, unlike `Or()`, and silently ignored the other twelve',
)
w(
  '  arguments the adapter passed it. The `mixed_query` benchmark was matching 96 153 entities instead',
)
w('  of 49 998.')
w(
  "- becsy's `perf` build has its assertions compiled out. On the default `maxShapeChangesPerFrame` it",
)
w(
  '  silently creates only *some* of the entities you ask for, and every query built on them comes back',
)
w("  short — with no error anywhere. Three of becsy's benchmarks were quietly iterating nothing.")
w()
w(
  'Structural benchmarks get the same treatment: `verify-structural.mjs` proves the add/remove work',
)
w('actually changes state, and because becsy defers structural changes to the frame boundary,')
w('`verify-becsy-coalesce.mjs` proves it is not collapsing an in-frame add+remove into nothing')
w(
  `(${f.becsyChecks.coalescing.inFrameUs}µs in-frame vs ${f.becsyChecks.coalescing.alternatingFramesUs}µs across alternating frames — it is doing the work).`,
)
w()
w('Every figure is the mitata average over a ≥1s CPU-time sample, after an explicit warmup.')
w()
w('## Head-to-head')
w()
w(
  'Each library at its fastest correct idiom, in microseconds, with the multiple of the hand-written',
)
w('baseline in brackets. Lower is better; **bold** is the fastest real library on that row.')
w()
w('| Benchmark | hand-written | apecs | bitECS | koota | becsy |')
w('| --- | --- | --- | --- | --- | --- |')
for (const bench of Object.keys(BENCHMARKS)) {
  const base = best(bench, 'baseline')
  const cells = ['apecs', 'bitecs', 'koota', 'becsy'].map((lib) => {
    const v = best(bench, lib)
    return { lib, v }
  })
  const winner = cells.filter((c) => c.v !== undefined).sort((a, b) => a.v - b.v)[0]?.lib
  const body = cells
    .map((c) => {
      const text = c.v === undefined ? '–' : `${fmt(c.v)} (${ratio(c.v, base)})`
      return c.lib === winner ? `**${text}**` : text
    })
    .join(' | ')
  w(`| \`${bench}\` | ${fmt(base)} | ${body} |`)
}
w()
w('What each row is measuring:')
w()
for (const [name, spec] of Object.entries(BENCHMARKS)) {
  w(`- **\`${name}\`** — ${spec.what} ${spec.measures}`)
}
w()
w('## The two tiers')
w()
w(
  'Most of these libraries offer an ergonomic idiom and a raw escape hatch, and the gap between them is',
)
w(
  'large enough that quoting one number per library hides the story. bitECS has no ergonomic tier — the',
)
w('raw arrays are the API. becsy has no raw tier — everything goes through a system.')
w()
w(
  '| Benchmark | apecs `each` | apecs `chunks` | koota `updateEach` | koota `useStores` | bitECS | becsy |',
)
w('| --- | --- | --- | --- | --- | --- | --- |')
for (const bench of Object.keys(BENCHMARKS)) {
  w(
    `| \`${bench}\` | ${fmt(tier(bench, 'apecs', 'ergonomic'))} | ${fmt(tier(bench, 'apecs', 'raw'))} | ` +
      `${fmt(tier(bench, 'koota', 'ergonomic'))} | ${fmt(tier(bench, 'koota', 'raw'))} | ` +
      `${fmt(tier(bench, 'bitecs', 'raw'))} | ${fmt(tier(bench, 'becsy', 'ergonomic'))} |`,
  )
}
w()
const overhead = r.timings.frame_overhead?.becsy
if (overhead) {
  const v = Object.values(overhead.variants)[0]
  w(
    `becsy's figures each include one \`world.execute()\` frame, which the others do not pay. Measured on`,
  )
  w(
    `its own that frame costs ${fmt(v.avg)}µs — negligible at these scales, so it is not distorting anything.`,
  )
  w()
}
w('## Memory')
w()
w(
  'Bytes per entity for a world of entities carrying Position + Velocity — two `f32` fields each, so',
)
w(
  '**16 bytes is the actual payload**. Everything above 16 is what the library charges for ids, masks,',
)
w('sparse sets, archetype bookkeeping and query caches.')
w()
w('Measured as absolute resident bytes at five world sizes, least-squares fitted — *not* as a')
w(
  "before/after delta, which subtracts two heap readings taken at different points in the collector's",
)
w(
  'life and is dominated by when it happened to compact. Measured that way, 100 000 entities came out',
)
w('*smaller* than 10 000. The check that the fit works: the hand-written baseline must land on 16.')
w()
w('| Library | Bytes/entity | Overhead above payload |')
w('| --- | --- | --- |')
for (const lib of LIBS) {
  const m = r.memory[lib]
  if (!m) continue
  const over =
    lib === 'baseline' ? '— (this *is* the payload)' : `${(m.perEntity / 16).toFixed(1)}× payload`
  w(`| ${TITLE[lib]} | ${m.perEntity.toFixed(1)} | ${over} |`)
}
w()
w('At 1 000 000 entities that is 38 MB for apecs against 237 MB for bitECS and 294 MB for koota.')
w()
w('## The finding that matters most: the ergonomic tier falls off a cliff at five traits')
w()
w("V8's inline caches hold four shapes before going megamorphic. Every library here that offers a")
w(
  'per-entity ergonomic accessor dispatches through a shared internal call site, and once a program',
)
w('uses enough distinct traits with it, that site tips over.')
w()
w(
  'ns per entity-visit, ergonomic tier, **one trait-count per process** — sweeping `k` inside a single',
)
w(
  'process lets earlier shapes pollute the dispatch site, which manufactures the cliff whether or not',
)
w('`k` causes it:')
w()
const sweep = f.traitCountSweep
w('| distinct traits | ' + sweep.ks.join(' | ') + ' |')
w('| --- |' + sweep.ks.map(() => ' --- |').join(''))
for (const lib of ['apecs', 'bitecs', 'koota', 'becsy']) {
  w(`| ${TITLE[lib]} | ` + sweep[lib].map((v) => v.toFixed(1)).join(' | ') + ' |')
}
w()
w(
  '- **apecs is the fastest ergonomic tier measured below five traits** (1.9–2.9 ns) and the worst hit',
)
w(
  '  above it: **17× slower at eight traits than at one.** Any real program uses more than four traits.',
)
w('- **becsy** has the same cliff in the same place, 7×.')
w('- **koota** degrades only 1.5×, but starts an order of magnitude behind.')
w('- **bitECS is immune** — flat at ~1.5 ns. It has no per-component dispatch to go megamorphic.')
w()
w(
  'SPEC §12.2 rule 2 says "no megamorphic call sites in the iteration path: cursor classes are per-trait,',
)
w(
  'not shared." Per-trait cursor classes are precisely what makes the shared dispatch site polymorphic.',
)
w('The rule is aiming at the right target and the mechanism defeats it.')
w()
w(
  "**apecs's `chunks` tier is completely immune** and is the fastest thing in this report — flat at",
)
w(
  `${f.traitCountSweep.apecsChunks.ns
    .slice(0, 4)
    .map((n) => n.toFixed(2))
    .join('/')} ns/entity through eight traits, against bitECS's ~1.5.`,
)
w()
w('Per-call costs, for sizing systems that run over small archetypes')
w(
  `(\`${f.apecsCallCost.script}\`): \`each\` is ${f.apecsCallCost.each.fixedNs} ns fixed + ${f.apecsCallCost.each.perEntityNs} ns/entity;`,
)
w(
  `\`chunks\` is ${f.apecsCallCost.chunks.fixedNs} ns fixed + ${f.apecsCallCost.chunks.perEntityNs} ns/entity.`,
)
w()
w('## Capability comparison: sorted queries')
w()
w(
  'Sorting is where apecs claims a feature the field mostly lacks. bitECS and becsy ship none; koota has',
)
w(
  '`QueryResult.sort()`, which re-sorts on demand. 100 000 entities iterated in sorted order every frame,',
)
w('microseconds:')
w()
w('| | keys never change | 1% of keys change per frame |')
w('| --- | --- | --- |')
for (const [k, label] of [
  ['apecs', 'apecs `sortBy`'],
  ['koota', 'koota `sort()`'],
  ['handwritten', 'hand-written `Array.sort` + gather'],
]) {
  w(
    `| ${label} | ${f.sortedQueries[k].static.toFixed(0)} | ${f.sortedQueries[k].drift.toFixed(0)} |`,
  )
}
w()
w(
  'apecs is **6–8× faster than koota** here, which is the headline. But it is also **2.3× slower than',
)
w('simply sorting an id array by hand**, and that deserves attention rather than a victory lap:')
w()
const si = f.sortedIsolation
w(
  `- Iterating the same query linearly costs ${si.plainEach} ns/entity. Iterating it sorted costs ${si.sortedEach} ns/entity — **${(si.sortedEach / si.plainEach).toFixed(0)}×**.`,
)
w(
  `- A hand-written gather over an identical precomputed order costs ${si.handWrittenGatherOverFixedOrder} ns/entity, so the gap is not memory locality; it is ~37 ns/entity of overhead inside the sorted iteration driver.`,
)
w(
  `- \`sorted.entities()\` on a view whose keys were **never touched** costs ${si.sortedEntitiesOnly} ns/entity, and that cost is flat at every world size (${Object.values(
    f.sortedStaticIsLinear.nsPerEntity,
  )
    .map((v) => v.toFixed(2))
    .join(' / ')} ns/entity at 1 k / 10 k / 100 k). It is O(n).`,
)
w()
w('SPEC §12.1 budgets `sorted-static` at **zero work** — "one `lastWriteTick` compare per matching')
w(
  'archetype." The measured cost is linear in entity count at every size, so that budget is not being met.',
)
w('This is the clearest actionable gap the comparison turned up.')
w()
w('## Reproducing')
w()
w('```bash')
w('cd bench/compare && npm install')
w('node run.mjs        # census, timings, memory -> results.json')
w('node report.mjs     # results.json + findings.json -> REPORT.md')
w('```')
w()
w('Supplementary measurements in `findings.json` each name the script that reproduces them.')

writeFileSync('REPORT.md', out)
console.log(`wrote REPORT.md (${out.split('\n').length} lines)`)
